"""Assemble the safety proof files and the *_checkXtr.ec sanity checks.

Same strategy as the correctness proofs (proof/amd64-barray):
  * memory variants (and everything independent of the array size) are proved
    about module M of the direct extraction extracted/Keccak1600_Jazz_safety.ec;
  * array variants are extracted at the dummy size _ASIZE = 999
    (extracted/Keccak1600_Jazz_ASIZE_safety.ec) and abstracted over the size by
    scripts/asize_transform.py (`safety_parts`): each layer becomes an abstract
    theory, parametrised by the array (op _ASIZE, clone ByteArray as A), whose
    module MM holds the abstracted procedures, followed by their safety
    specifications and proofs. Layers other than the subreadwrite one clone
    ReadWriteArraySafety as RW;
  * extracted/<layer>_checkXtr.ec instantiates each theory at 999 and checks
    M.f ~ MM.f by sim, then transfers each safety lemma to the extraction
    (this is also the pattern for a client using the library at a given size).
"""
import re, sys, json, os
import gen

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)          # proof/amd64-barray/safety
REPO = os.path.dirname(os.path.dirname(os.path.dirname(ROOT)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
import asize_transform

MODEL = ROOT + "/extracted/Keccak1600_Jazz_safety.ec"
SKEL = ROOT + "/extracted/Keccak1600_Jazz_safety.skel"
MODEL_A = ROOT + "/extracted/Keccak1600_Jazz_ASIZE_safety.ec"
SKEL_A = ROOT + "/extracted/Keccak1600_Jazz_ASIZE_safety.skel"

RW_THEORY = "ReadWriteArraySafety"
ASIZE_SMT = "_ASIZE_ge0 _ASIZE_max"

def lemma_headers(path):
    s = open(path).read()
    out = {}
    for b in re.split(r'(?m)^(?=lemma )', s)[1:]:
        m = re.match(r'lemma (\S+)_proof(.*?)\nproof\.', b, re.S)
        out[m.group(1)] = "lemma " + m.group(1) + "_proof" + m.group(2)
    return out

def asize_subst(text):
    return "".join(asize_transform.body_subst(l, "barray") for l in text.splitlines(keepends=True))

_G = {}
def models():
    if not _G:
        _G['mem'] = gen.Gen(MODEL)
        _G['arr'] = gen.Gen(MODEL_A)
        _G['hmem'] = lemma_headers(SKEL)
        _G['harr'] = lemma_headers(SKEL_A)
        _G['src_arr'] = open(MODEL_A).read()
    return _G

def lemma(G, H, x, ann, manual, default_smt, qual=None, sub=None, default_smt2=None):
    if x in manual:
        body = manual[x].strip()
    else:
        a = dict(ann.get(x, {}))
        if default_smt:
            a['SMT'] = (a.get('SMT', '') + ' ' + default_smt).strip()
        if default_smt2 and 'SMT2' not in a:
            a['SMT2'] = default_smt2
        s, need, hint = G.script(x, a, qual)
        miss = [k for k in need if k not in a]
        body = gen.subst(s, a)
        if miss: body = "(* MISSING: " + " ".join(sorted(miss)) + " *)\n" + body
        if hint: print(f"note: {x}: a join formula {' '.join(sorted(hint))} would merge more branches", file=sys.stderr)
    text = H[x] + "\nproof.\nrewrite /" + x + "_spec; proc.\n" + body + "\nqed.\n"
    return sub(text) if sub else text

def theory_header(name, rw, checkfile):
    t = f"""(* -------------------------------------------------------------------- *)
(* Array variants, abstracted over the array size.                       *)
(* -------------------------------------------------------------------- *)
abstract theory {name}.

op _ASIZE: int.

axiom _ASIZE_ge0: 0 <= _ASIZE.
axiom _ASIZE_u64: _ASIZE < W64.modulus.

(* the ui64 range conditions of the model are stated with the literal 2^64-1 *)
lemma _ASIZE_max: _ASIZE <= 18446744073709551615.
proof. smt(_ASIZE_u64 pow2_64). qed.

clone import ByteArray as A
 with op size <- _ASIZE
      proof ge0_size by exact _ASIZE_ge0.
"""
    if rw:
        t += f"""
clone import {RW_THEORY} as RW
 with op _ASIZE <- _ASIZE,
      theory A <- A
      proof _ASIZE_ge0 by exact _ASIZE_ge0
      proof _ASIZE_u64 by exact _ASIZE_u64.
"""
    else:
        t += """
lemma A_init_cell_ones k : A.is_init_cell (A.init_arr (W8.of_int 255)) k = true.
proof. by rewrite eqT; apply (A.init_arrP witness). qed.
lemma A_init_cell_zeros k : A.is_init_cell (A.init_arr (W8.of_int 0)) k = !(0 <= k < _ASIZE).
proof. by rewrite /A.is_init_cell; case: (0 <= k < _ASIZE) => //= h; rewrite A.initE h /= W8.to_uint_eq. qed.
hint simplify A_init_cell_ones, A_init_cell_zeros.
"""
    callees = "\n   the subreadwrite callees taken from RW.MM," if rw else ""
    t += f"""
(* The array procedures of Keccak1600_Jazz_ASIZE_safety (extracted at
   _ASIZE = 999), with BArray999 replaced by A and 999 by _ASIZE,{callees}
   the size-independent callees taken from Keccak1600_Jazz_safety.M, and
   their safety specifications restated over MM. Generated by
   scripts/asize_transform.py --safety; checked by
   ../extracted/{checkfile}. *)
"""
    return t

THEORIES = []   # (theory, presets, proof module, checkXtr file) built in this run

def build(items, ann, manual, out_path, default_smt="", default_smt2=None):
    """items: ('raw', text) | ('gen', proc)    -- memory/size-independent proc (module M)
            | ('theory', dict(name=, presets=[..], check=<file>, rw=bool))
                                               -- abstract theory of array procs (module MM)"""
    G = models()
    parts = []
    for item in items:
        kind, x = item
        if kind == 'raw':
            parts.append(x.strip() + "\n")
        elif kind == 'gen':
            parts.append(lemma(G['mem'], G['hmem'], x, ann, manual, default_smt, default_smt2=default_smt2))
        else:
            rw = x.get('rw', True)
            mm, specs, names = asize_transform.safety_parts(G['src_arr'], x['presets'])
            parts.append(theory_header(x['name'], rw, x['check']))
            parts.append(mm)
            parts.append("(* safety specifications *)\n\n" + specs)
            qual = {n: "RW." for n in asize_transform.SUBRW_PROCS} if rw else {}
            smt = (default_smt + " " + ASIZE_SMT).strip()
            for n in names:
                parts.append(lemma(G['arr'], G['harr'], n, ann, manual, smt, qual, asize_subst, default_smt2=default_smt2))
            parts.append(f"end {x['name']}.\n")
            mod = os.path.splitext(os.path.basename(out_path))[0]
            THEORIES.append((x['name'], names, mod, x['check']))
            write_checkxtr(x['name'], names, mod, x['check'])
    open(out_path, "w").write("\n".join(parts))

def write_checkxtr(theory, names, mod, fname):
    H = models()['harr']
    out = [f"""(* Generated by ../gen (build.py): do not edit. *)
require import AllCore IntDiv CoreMap List Distr.
from Jasmin require import JModel_x86 Jcheck JSafety.

(** Sanity check: the module MM of the abstract theory {theory} ({mod}.ec)
    is the abstraction over the array size of the procedures extracted at
    _ASIZE = 999 (Keccak1600_Jazz_ASIZE_safety), and the safety
    specifications stated there over MM are those of the extraction. This is
    also how a client uses the library at a given size: instantiate the theory,
    prove its own extraction equivalent to MM (sim) and transfer the safety
    lemmas (conseq). *)

require import Keccak1600_Jazz_ASIZE_safety.
require import BArray999.
require import {mod}.

clone import {theory} as A999
 with op _ASIZE <- 999,
      theory A <- BArray999
      proof _ASIZE_ge0 by done, _ASIZE_u64 by done.
"""]
    for n in names:
        out.append(f"""equiv a999_{n}_eq:
 M.{n} ~ MM.{n}
 : ={{arg}} ==> ={{res}}
by sim.
""")
    for n in names:
        hdr = H[n]
        m = re.match(r"lemma \S+_proof(.*?):\s*\((\S+)_spec(.*)\)\.?\s*$", hdr, re.S)
        args = m.group(1).strip()
        out.append(f"""lemma a999_{n}_safety {args} :
  Keccak1600_Jazz_ASIZE_safety.{n}_spec {args}.
proof.
rewrite /Keccak1600_Jazz_ASIZE_safety.{n}_spec.
move: (A999.{n}_proof {args}); rewrite /A999.{n}_spec => h.
by conseq a999_{n}_eq h => /> /#.
qed.
""")
    open(ROOT + "/extracted/" + fname, "w").write("\n".join(out))
